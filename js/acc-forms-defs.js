export const N = v => {
  if (v == null || v === '') return NaN;
  const s = String(v).replace(/[٠-٩]/g, d => '٠١٢٣٤٥٦٧٨٩'.indexOf(d)).replace(/[٫,]/g, '.').replace(/[^\d.\-]/g, '');
  return s === '' ? NaN : parseFloat(s);
};
const ok = x => Number.isFinite(x);
const r1 = x => Math.round(x * 10) / 10;
const pct = (a, b) => (ok(a) && ok(b) && b > 0 ? r1(a / b * 100) : '');
const diff = (a, b) => { const x = N(a), y = N(b); return ok(x) && ok(y) ? (y - x > 0 ? '+' : '') + r1(y - x) : ''; };
const trend = (a, b, inv) => { const x = N(a), y = N(b); if (!ok(x) || !ok(y)) return ''; if (y === x) return '= ثبات'; const up = y > x; return up ? (inv ? '▲ ارتفاع' : '▲ تقدم') : (inv ? '▼ انخفاض' : '▼ تراجع'); };
const rows = (d, id) => (Array.isArray(d[id]) ? d[id] : []);
const filled = r => r && Object.keys(r).some(k => !k.startsWith('_') && String(r[k] ?? '').trim() !== '');
const avg = a => { const v = a.filter(ok); return v.length ? r1(v.reduce((s, x) => s + x, 0) / v.length) : ''; };
const days = (a, b) => { if (!a || !b) return NaN; return Math.round((new Date(b) - new Date(a)) / 86400000); };

